  static const Color secondaryLight = Color(0xFF3B82F6);

  // Background
  static const Color bgDark = Color(0xFF0F0F14);
  static const Color bgCard = Color(0xFF1A1A24);
  static const Color bgCardLight = Color(0xFF242434);
  static const Color bgElevated = Color(0xFF2A2A3C);

  // Surface
  static const Color surface = Color(0xFF16161F);
  static const Color surfaceLight = Color(0xFF1E1E2D);

  // Text
